"""Write the headers the A7 IV helper (helper/readcheck.c) needs to carry the A1 II 4.00 designs (A1 II port, 2026-11-26).

  C:\\Python313\\python.exe -B gen_a1m2_write.py

Made from helper_fx30/gen_fx30_write.py (the sensor design writes several stored drive-parameter records in two timing variants: readcheck.c's
MULTI_REC switch), helper_fx3/gen_fx3_write.py (the XAVC S-I step, levels 19/20 again) and helper_s3/gen_s3_write.py (the C3 routine in
appFw.so, levels 19/20 with MP_LIB "appFw.so"). The A1 II's designs (modding/A1M2_PORT.md and its part notes):
  expected_sites_ogsq_a1m2_v1.h              levels 5/6 (L5/L6): 13 table/record sites and the four stored records (0x820, 0x2820, 0x8c0, 0x28c0)
  expected_sites_ogh2880_a1m2_v1.h           levels 5/6 (R5/R6): the real-rows alternative, the same sites with other record bytes
  expected_sites_fhband_a1m2_v1.h            levels 5/6 (B5/B6, kit v2 test0): the sensor window at full height only (read-out span, 3 matrix cells, 4 stored records)
  expected_sites_ogbb_a1m2_v1.h              levels 5/6 (T5/T6, kit v3 test5): the full design's sensor side with the stock-size 2,446-row stage taken from
                                             active row 450 (the bottom band): the same 13 sites and four stored records as L5, other record bytes
  expected_words_outsz2560_a1m2_v1.h         levels 16/17 (L16/L17): the output-size word and its guards
  expected_words_lcdfill_a1m2_v1.h           levels 16/17 (S16/S17): the rear screen filled (fit word) and the three frame rectangles
  expected_words_fehold_a1m2_v1.h            levels 16/17 (F16/F17, kit v2): one code word, the resize set-up keeps the records' first-scaler size
  expected_mp_ogfile2560_hs_s_a1m2_v2.h      levels 19/20 (L19/L20): encoder side with the two MP4 header heights
  expected_mp_ogfile2560_hs_s_a1m2_v1.h      levels 19/20 (N19): the same without the heights (--no-meta)
  expected_mp_ogfilesi2560_a1m2_v1.h         levels 19/20 (I19/I20): XAVC S-I 4K at 3840x2560
  expected_mp_lcdcycle_a1m2_v1.h             levels 19/20 (C19/C20): the C3 preview routine and its hook in appFw.so
No raw-write-buffer step (the stock unit holds the 2,896-row stage: modding/A1M2_PORT_DMM_SIZE.md) and no playback step (the A1 II's
decoder takes the A7 IV's 8K row: A1M2_PORT_ENCODER.md). Every stock byte is compared with the 4.00 files here.
"""
import hashlib
import json
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/a1m2_400/0700_part_image/dev"
DES = ROOT / "modding/designs"
BASE = 0x108000
IMAGE = (EX / "nflasha8/cpapp-b.bin").read_bytes()
IMAGE_END = BASE + len(IMAGE)
CP_DATA_LO = 0xD00000                                 # every cpapp-b.bin site of the sensor designs lies in its tables (records 0xdf6844 on)
SIZE_TABLE = (0x1938488, 0x1938488 + 0x80)             # the movie size table (build/emu_size_table.py a1m2_400; A1M2_PORT_DMM_SIZE.md)
DESC, DSIZE, UNIT, CLIP, COMB = 0x3AB2D4, 0x90, 0x3AB234, 0x3A9158, 0x2D2CA8     # build_ogfile.OTHER_BUILDS["a1m2_400"] (A1M2_PORT_ENCODER.md)
PROFILE_END = 0x3DA8B4 + 315 * 0x100                  # the second profile table's end
REC = 0x170
MODES = (0x820, 0x2820, 0x8C0, 0x28C0)
APPFW_MAP = 0x4D0E000                                  # appFw.so's first mapping: its r-x segment (file size 0x4d0d8a5) in whole pages
hx = lambda b: ", ".join("0x%02x" % x for x in b)
HEAD = "/* Generated by helper_a1m2/gen_a1m2_write.py from modding/designs/%s.json (A1 II 4.00). Do not edit. */"


def design(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d.get("build", "a1m2_400") == "a1m2_400", name
    return d


def sites_header(name):
    """Levels 5/6: the table/record sites and the four stored records (MULTI_REC, NTSC and PAL variants)."""
    d = design(name)
    assert d["artifact_sha256"] == hashlib.sha256(IMAGE).hexdigest() and d["record_size"] == REC
    assert [int(m, 16) for m in d["modes"]] == list(MODES)
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    out = [HEAD % name, "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and IMAGE[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and CP_DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's tables"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    assert len(sites) == {"fhband_a1m2_v1": 4}.get(name, 13)          # the band diagnostic (B5): the read-out span + 3 matrix cells
    squeeze = bool(d["stored_record_extra"])
    srs = d["stored_records"]
    offs = None
    stock, new = [], []
    for m in MODES:
        sr = srs[hex(m)]
        o = [int(x, 16) for x in sr["offsets_that_differ"]]
        assert offs is None or o == offs, "the modes' record sites differ"
        offs = o
        st_m, nw_m = [], []
        for v in ("ntsc", "pal"):
            s, n = bytes.fromhex(sr[v]["stock"]), bytes.fromhex(sr[v]["design"])
            assert len(s) == len(n) == REC and s[4:8] == b"\x02\x01\x02\x01"        # 2x2 binned: H 2/1, V 2/1
            assert n[4:8] == (b"\x02\x01\x1b\x10" if squeeze else b"\x02\x01\x02\x01"), n[4:8].hex()
            assert all(s[k] == n[k] for k in range(REC) if k not in o), "a changed byte outside the site list"
            st_m.append(bytes(s[k] for k in o))
            nw_m.append(bytes(n[k] for k in o))
        assert len({st_m[0], st_m[1], nw_m[0], nw_m[1]}) == 4, "a variant's bytes equal another's: the variant could not be told"
        stock.append(st_m)
        new.append(nw_m)
    assert (offs[:2] == [6, 7]) == squeeze and 2 < len(offs) <= 128
    arr = lambda t: "{ " + ", ".join("{ " + ", ".join("{ %s }" % hx(v) for v in m) + " }" for m in t) + " }"
    out += ["#define MULTI_REC 1",
            "#define N_RECS %d" % len(MODES), "#define REC_VARIANTS 2",
            '#define REC_VARIANTS_TEXT "NTSC 60 Hz or PAL 50 Hz"',
            "#define REC_BYTES %d" % len(offs),
            "static const u32 rec_modes[N_RECS] = { %s };" % ", ".join("0x%x" % m for m in MODES),
            "static const char *const rec_mode_text[N_RECS] = { %s };" % ", ".join('"%#x"' % m for m in MODES),
            'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
            "static const unsigned short rec_offs[REC_BYTES] = { %s };" % ", ".join("0x%x" % k for k in offs),
            "/* per mode (rec_modes order), per variant (NTSC, PAL): the bytes at rec_offs before and after */",
            "static const u8 rec_stock[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(stock),
            "static const u8 rec_new[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(new),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + len(MODES)),
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), [hex(m) for m in MODES], hashlib.sha256((DES / f"{name}.json").read_bytes()).hexdigest()[:16]


# fehold_a1m2_v1 (kit v2): one CODE word of the resize set-up 0x521438, the branch over the A1 II's first-scaler override; its guards are
# the 16 code bytes before and after (build/build_ram_words_a1m2.py --fehold, which decodes them)
FEHOLD_SITE, FEHOLD_GUARDS = (0x521760, 0x521764), ((0x521750, 0x521760), (0x521764, 0x521774))


def regions(name):
    if name == "outsz2560_a1m2_v1":
        return (SIZE_TABLE,), ()
    if name == "fehold_a1m2_v1":
        return (FEHOLD_SITE,), FEHOLD_GUARDS
    r = design(name)["word_regions"]                   # lcdfill_a1m2_v1 (build/build_lcd_a1m2.py): sites only in FIT and FRAMES
    to = lambda p: (int(p[0], 16), int(p[1], 16))
    return (to(r["FIT"]),) + tuple(to(p) for p in r["FRAMES"]), tuple(to(p) for p in r["guard_only"])


def words_header(name):
    d = design(name)
    assert d["kind"] == "ram_words"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    site_regions, guard_only = regions(name)
    within = lambda a, n, rs: any(lo <= a and a + n <= hi for lo, hi in rs)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and within(a, 4, site_regions) for a, o, n in sites), name
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards), name
    for a, o, _ in sites:                                  # words inside the loaded image: the file's bytes
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + 4] == o
    for a, b in guards:
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + len(b)] == b
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [HEAD % name, "/* Words of the coprocessor's tables (cpapp-b.bin 4.00): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name, "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };", "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    (OUT / f"expected_words_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(guards)


def mp_header(name):
    """helper_fx30/gen_fx30_write.mp_header with this build's tables (the encoder side, and the S-I step)."""
    d = design(name)
    av, lm = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/libmpr.so").read_bytes()
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    code_ok = {int(g["site"], 16): g["guards"] for g in d.get("libmpr_code_guards", [])}
    assert all(not p["code"] or (p["binary"] == "libmpr.so" and int(p["file_off"], 16) in code_ok) for p in d["patches"]), \
        "not a data-only encoder-side design (a code site must be in libmpr.so and named in libmpr_code_guards)"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    for x in d["descriptors"]:
        o = DESC + x["descriptor"] * DSIZE + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if off in code_ok:
            for g in code_ok[off]:
                a, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
                assert lm[a:a + len(b)] == b and len(b) <= 16
                g_lm.append((a, b))
            continue
        assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
        g_lm.append((off - 6, lm[off - 6:off]))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(a < s + len(o) and s < a + len(b) for a, b in guards for s, _, o, _ in sites), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert (CLIP & ~0xFFF) <= first and first + span <= ((PROFILE_END + 0xFFF) & ~0xFFF), "an av-cam.bin site lies outside the pages of its tables"
    phoff, phentsize, phnum = struct.unpack_from("<Q", lm, 0x20)[0], *struct.unpack_from("<HH", lm, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [HEAD % name,
           "/* av-cam.bin %s..., libmpr.so %s... (4.00). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


def mp_appfw_header(name="lcdcycle_a1m2_v1"):
    """helper_s3/gen_s3_write.mp_appfw_header for the A1 II's C3 routine (build/build_lcdcycle_a1m2.py): code sites in appFw.so, written in the
    design's order (every cave byte, then the branch into the cave), put back in reverse (MP_LM_ORDERED). The av-cam.bin table holds only the
    two standard guards (the A1 II's unit row 2 and clip row 5), so nothing is written there. Guards in appFw.so: the file's first 16 bytes,
    the 16 file bytes just before the cave, 16 bytes on each side of the hooked instruction, and the first 16 bytes of each function the
    routine calls (dlsym's .plt stub, the system-mode accessor, the layout wrapper). The cave lies in the zero tail of the first segment's
    last page (file size 0x4d0d8a5, mapping 0x4d0e000), as the A7 IV's."""
    d = design(name)
    av, lib = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/appFw.so").read_bytes()
    assert d["generated_by"] == "build/build_lcdcycle_a1m2.py" and d["library"] == "appFw.so" and all(p["binary"] == "appFw.so" and p["code"] for p in d["patches"])
    assert d["artifact_sha256"] == {"appFw.so": hashlib.sha256(lib).hexdigest()}, "the design was made from another appFw.so"
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    phoff, phentsize, phnum = struct.unpack_from("<Q", lib, 0x20)[0], *struct.unpack_from("<HH", lib, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lib, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lib, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and load0[5] == load0[6] == 0x4D0D8A5
    mapped = (load0[5] + 0xFFF) & ~0xFFF
    assert mapped == APPFW_MAP == int(d["cave"]["mapping_bytes"], 16)
    sites = []
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) <= 16 and old != new and lib[off:off + len(old)] == old and off + len(old) <= mapped, "a site's old bytes are not the file's"
        assert p["kind"] == "hook" or (off >= load0[5] and not any(old)), "a cave byte inside the segment's own bytes, or not zero"
        sites.append((off, 1, old, new))
    hooks = [s for s, p in zip(sites, d["patches"]) if p["kind"] == "hook"]
    cave0 = min(s[0] for s, p in zip(sites, d["patches"]) if p["kind"] == "cave")
    assert len(hooks) == 1 and d["patches"][-1]["kind"] == "hook", "the hook must come last (apply order)"
    g_lib = [(0, lib[:16]), (cave0 - 0x18, lib[cave0 - 0x18:cave0 - 8])]
    for off, _, _, _ in hooks:
        g_lib += [(off - 16, lib[off - 16:off]), (off + 4, lib[off + 4:off + 20])]
    for fn in sorted(int(v, 16) for v in d["calls"].values()):
        g_lib.append((fn, lib[fn:fn + 16]))
    srt = sorted(sites + [(a, 0, b, b"") for a, b in g_lib])
    assert all(srt[k][0] + len(srt[k][2]) <= srt[k + 1][0] for k in range(len(srt) - 1)), "entries overlap"
    table = [(a, 0, b, b"") for a, b in g_lib] + sites   # guards first (checked only), then the sites in apply order
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    avs = sorted((a, 0, b, b"") for a, b in g_av)
    first = avs[0][0] & ~0xFFF
    span = ((max(a + len(b) for a, _, b, _ in avs) - first) + 0xFFF) & ~0xFFF
    out = [HEAD % name,
           "/* appFw.so %s... (4.00). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */" % d["artifact_sha256"]["appFw.so"][:16],
           '#define MP_DESIGN "%s"' % name,
           '#define MP_LIB "appFw.so"                 /* the mp_lm table is in appFw.so */',
           "#define MP_LM_ORDERED 1                    /* mp_lm sites in apply order (cave, then the hook); put back in reverse */",
           "#define MP_AV_FIRST 0x%xUL                 /* av-cam.bin: two guards only, nothing written there */" % first,
           "#define MP_AV_BYTES 0x%xUL" % span]
    if len(table) > 96:
        out.append("#define MP_MAX %d                         /* room for the entries of the appFw.so table (levels 19 and 20) */" % ((len(table) + 31) & ~31))
    out.append("struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };")
    for var, rows, what in (("mp_av", avs, "av-cam.bin"), ("mp_lm", table, "appFw.so")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, what))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in rows]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {"sites": len(sites), "hooks": len(hooks), "guards": len(g_lib), "table": len(table), "mapped": hex(mapped),
            "cave": (hex(cave0), hex(max(s[0] + len(s[2]) for s in sites[:-1])))}


